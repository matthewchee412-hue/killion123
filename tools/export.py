"""Write the tiered banks out as Luau ModuleScripts + a drag-in .rbxmx model."""
import json, re, shutil
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path("/home/claude/shrimpillion")
OUT = ROOT / "out"
SRC = OUT / "ShrimpillionAnswers"
CHUNK = 90_000  # characters per bank ModuleScript

banks = json.loads((OUT / "banks.json").read_text())

if SRC.exists():
    shutil.rmtree(SRC)
(SRC / "Banks").mkdir(parents=True)

def clean(name):
    # the line format uses | and newlines; long strings use ]==]
    return name.replace("|", "/").replace("\n", " ").replace("]==]", "]")

modules = {}   # relative path -> source
cat_rows = []
for cid, cat in banks.items():
    lines = []
    for e in cat["entries"]:
        names = [clean(e["d"])] + [clean(a) for a in e["a"]]
        lines.append(f'{e["t"]}' + "|".join(names))
    parts, cur, size = [], [], 0
    for ln in lines:
        if size + len(ln) + 1 > CHUNK and cur:
            parts.append(cur); cur, size = [], 0
        cur.append(ln); size += len(ln) + 1
    if cur:
        parts.append(cur)
    for i, p in enumerate(parts, 1):
        mod = f"Bank_{cid}" if len(parts) == 1 else f"Bank_{cid}_{i}"
        body = "\n".join(p)
        assert "]==]" not in body and "]]>" not in body
        modules[f"Banks/{mod}"] = (
            f"-- {cat['name']} answer bank (part {i}/{len(parts)}). Generated: one answer per line,\n"
            f"-- first char = rarity tier, then display name, then | nicknames.\n"
            f"return [==[\n{body}\n]==]\n")
    counts = [sum(1 for e in cat["entries"] if e["t"] == t) for t in range(5)]
    cat_rows.append((cid, cat["name"], cat["prompt"], len(cat["entries"]), len(parts), counts))

cat_src = ["--[[\n\tCategories — every answer bank, with the prompt players see.\n"
           "\tGenerated by the Shrimpillion bank builder; counts are answers per category.\n]]\n",
           "local list = {"]
for cid, name, prompt, n, parts, counts in cat_rows:
    cat_src.append(f'\t{{ id = "{cid}", name = "{name}", prompt = "{prompt}", count = {n}, parts = {parts}, '
                   f'tierCounts = {{ {", ".join(map(str, counts))} }} }},')
cat_src.append("}\n\nlocal byId = {}\nfor _, c in list do\n\tbyId[c.id] = c\nend\n\n"
               "return { list = list, byId = byId }\n")
modules["Categories"] = "\n".join(cat_src)
from wordfreq import top_n_list
common = []
seen = set()
for w in top_n_list("en", 40000):
    k = re.sub(r"[^a-z0-9]", "", w.lower())
    if len(k) >= 3 and k.isalpha() and k not in seen:
        seen.add(k); common.append(k)
    if len(common) >= 30000:
        break
modules["CommonWords"] = ("-- ~30k everyday English words (from wordfreq), used so real words are never\n"
                          "-- auto-corrected into answers. Generated.\nreturn [==[" + " ".join(common) + "]==]\n")
for name in ["AnswerMatcher", "Rarity", "Blocklist", "Luck"]:
    modules[name] = (ROOT / "luau" / f"{name}.luau").read_text()

shutil.copy(ROOT / "luau" / "README.md", SRC / "README.md")
for rel, src in modules.items():
    path = SRC / f"{rel}.luau"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(src)

# ---- .rbxmx model: Folder ShrimpillionAnswers { AnswerMatcher, Rarity, Blocklist, Categories, Banks/ }
ref = [0]
def nref():
    ref[0] += 1
    return f"RBX{ref[0]:08X}"

def module_xml(name, src):
    assert "]]>" not in src
    return (f'<Item class="ModuleScript" referent="{nref()}"><Properties>'
            f'<string name="Name">{escape(name)}</string>'
            f'<ProtectedString name="Source"><![CDATA[{src}]]></ProtectedString>'
            f'</Properties></Item>')

top = [module_xml(n, modules[n]) for n in ["AnswerMatcher", "Rarity", "Blocklist", "Luck", "Categories", "CommonWords"]]
bank_items = [module_xml(rel.split("/", 1)[1], src) for rel, src in modules.items() if rel.startswith("Banks/")]
xml = ('<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" '
       'xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" '
       'xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">'
       f'<Item class="Folder" referent="{nref()}"><Properties><string name="Name">ShrimpillionAnswers</string></Properties>'
       + "".join(top)
       + f'<Item class="Folder" referent="{nref()}"><Properties><string name="Name">Banks</string></Properties>'
       + "".join(bank_items) + "</Item></Item></roblox>")
(OUT / "ShrimpillionAnswers.rbxmx").write_text(xml, encoding="utf-8")

total = sum(r[3] for r in cat_rows)
print(f"{len(cat_rows)} categories, {total} answers, {len(bank_items)} bank modules, "
      f"rbxmx {len(xml)/1e6:.2f} MB")
